import json
from collections import Counter

from .playbooks import PREVENT, SCRUB, steps_for
from .rank import ORDER, first_seen

CHANNEL_TEXT = {
    "pushed": "committed and pushed (reachable from a remote)",
    "history-local": "committed, not pushed to any remote",
    "local-untracked": "in the working tree, not ignored by git",
    "local-ignored": "in the working tree, git-ignored (local only)",
    "file": "in a file (not a git repo)",
    "image": "baked into a Docker image",
    "ci-log": "printed in a CI log",
}
MAX_LOCS = 4


def _locs(f):
    groups: dict = {}
    for l in f.locations:
        g = groups.setdefault(l.path, {"line": None, "commits": [], "notes": []})
        g["line"] = g["line"] or l.line
        if l.commit:
            g["commits"].append((l.date, l.commit[:7], l.author))
        for n in (l.detail if l.detail != "history" else "", "deleted in a later layer but still recoverable" if l.deleted_later else ""):
            if n and n not in g["notes"]:
                g["notes"].append(n)
    out = []
    for path, g in groups.items():
        s = f"{path}:{g['line']}" if g["line"] else path
        if g["commits"]:
            d, sha, who = min(g["commits"])
            n = len(g["commits"])
            g["notes"].append(f"in {n} commit{'s' if n > 1 else ''}, first {sha} on {d[:10]} by {who}")
        out.append(s + (f" ({'; '.join(g['notes'])})" if g["notes"] else ""))
    if len(out) > MAX_LOCS:
        out = out[:MAX_LOCS] + [f"... and {len(out) - MAX_LOCS} more files"]
    return out


def _where(f):
    ch = sorted({l.channel for l in f.locations}, key=lambda c: list(CHANNEL_TEXT).index(c))
    text = [CHANNEL_TEXT[c] for c in ch]
    if "pushed" in ch and not any(l.detail != "history" and l.channel == "pushed" and not l.commit for l in f.locations):
        text.append("no longer in the latest files, but still in git history")
    return text


def summary(findings):
    c = Counter(f.tier for f in findings)
    return ", ".join(f"{c[t]} {t.lower()}" for t in ("CRITICAL", "HIGH", "MEDIUM", "LOW") if c[t]) or "no findings"


def to_text(findings, stats) -> str:
    out = [f"leakguard: {stats}", f"Result: {summary(findings)}", ""]
    for i, f in enumerate(findings, 1):
        out.append(f"{i}. [{f.tier} {f.score}] {f.rule.label}  {f.redacted}  id:{f.fingerprint}")
        for w in _where(f):
            out.append(f"   exposure: {w}")
        for n in f.notes:
            out.append(f"   note: {n}")
        for s in _locs(f):
            out.append(f"   at {s}")
        fs = first_seen(f)
        if fs:
            out.append(f"   first committed: {fs[:10]}")
        out.append("")
    if findings:
        out.append("Rotation steps: re-run with --rotation ROTATION.md. Secrets are never printed in full.")
    return "\n".join(out).rstrip() + "\n"


def to_json(findings, stats) -> str:
    return json.dumps({"summary": summary(findings), "scanned": stats, "findings": [{
        "tier": f.tier, "score": f.score, "rule": f.rule.id, "provider": f.rule.provider, "label": f.rule.label,
        "fingerprint": f.fingerprint, "redacted": f.redacted, "power": f.power, "exposure": f.exposure,
        "validity": f.validity, "notes": f.notes, "exposed_as": _where(f), "first_committed": first_seen(f),
        "locations": [{k: v for k, v in vars(l).items() if v not in ("", None, False)} for l in f.locations],
    } for f in findings]}, indent=2)


def to_rotation(findings, stats) -> str:
    out = ["# Secret rotation plan", "", f"Generated by leakguard ({stats}). Result: {summary(findings)}.", "",
           "**Order matters: rotate first, then check for misuse, then clean up history.** Removing a secret from git does not make it safe again.",
           "Dashboard paths change over time; the goal of each step is stated so you can find the current equivalent.", ""]
    actionable = [f for f in findings if ORDER[f.tier] >= 1]
    low = [f for f in findings if ORDER[f.tier] < 1]
    for i, f in enumerate(actionable, 1):
        url, steps = steps_for(f)
        out += [f"## {i}. {f.rule.label}: {f.redacted} ({f.tier}, score {f.score})", "",
                f"Fingerprint `{f.fingerprint}` (add to `.leakguardignore` if it is a false positive).", ""]
        out += [f"- Exposure: {w}" for w in _where(f)]
        out += [f"- Note: {n}" for n in f.notes]
        fs = first_seen(f)
        if fs:
            out.append(f"- First committed {fs[:10]}: check provider logs from that date on.")
        out += ["", "Where:"] + [f"- `{s}`" for s in _locs(f)] + ["", "Steps:"]
        n = 1
        if f.rule.id != "env-file" and url:
            out.append(f"{n}. Open {url}")
            n += 1
        for s in steps:
            out.append(f"{n}. {s}")
            n += 1
        seen = set()
        for l in f.locations:
            if l.channel in SCRUB and l.channel not in seen and f.rule.id != "env-file":
                seen.add(l.channel)
                for s in SCRUB[l.channel]:
                    out.append(f"{n}. {s}")
                    n += 1
        out.append("")
    if low:
        out += ["## Low priority", ""] + [f"- {f.rule.label} `{f.redacted}` id:{f.fingerprint}: {', '.join(_where(f))}" for f in low] + [""]
    out += ["## Prevent the next one", ""] + [f"- {p}" for p in PREVENT] + [""]
    return "\n".join(out)
